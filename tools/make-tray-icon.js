'use strict';
/**
 * Generates the tray icon and writes it as a source module.
 *
 * The icon is emitted as base64 PNG into `src/desktop/tray-icon.js` rather than
 * as a binary asset, for one reason: the previous build referenced generated
 * images that were never committed, so a clean checkout could not package. A
 * source file cannot be forgotten by .gitignore.
 *
 *   node tools/make-tray-icon.js
 *
 * Grayscale + alpha (PNG colour type 4) — a macOS template image is black plus
 * transparency, and the OS recolours it for light, dark and menu-bar states.
 * Drawing is supersampled 4x for antialiasing; no dependencies.
 */

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const SS = 4; // supersampling factor

/** A rotary encoder seen end-on: body ring, shaft hub, and a needle. */
function drawIcon(size) {
  const n = size * SS;
  const cx = n / 2 - 0.5;
  const cy = n / 2 - 0.5;
  const cover = new Float64Array(n * n);

  const ringR = n * 0.40;
  const ringW = n * 0.095;
  const hubR = n * 0.10;
  const needleLen = n * 0.34;
  const needleW = n * 0.085;
  // Up and to the right: reads as "in motion" rather than as a clock hand.
  const angle = -Math.PI / 4;
  const nx = Math.cos(angle);
  const ny = Math.sin(angle);

  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      const dx = x - cx;
      const dy = y - cy;
      const r = Math.hypot(dx, dy);

      let on = 0;
      // Ring
      if (Math.abs(r - ringR) <= ringW / 2) on = 1;
      // Hub
      if (r <= hubR) on = 1;
      // Needle: distance to the segment from the centre outward
      const t = Math.max(0, Math.min(needleLen, dx * nx + dy * ny));
      const px = dx - nx * t;
      const py = dy - ny * t;
      if (Math.hypot(px, py) <= needleW / 2) on = 1;

      cover[y * n + x] = on;
    }
  }

  // Box-downsample the supersampled coverage into the final alpha channel.
  const out = Buffer.alloc(size * size * 2);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let sum = 0;
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          sum += cover[(y * SS + sy) * n + (x * SS + sx)];
        }
      }
      const a = Math.round((sum / (SS * SS)) * 255);
      const i = (y * size + x) * 2;
      out[i] = 0;       // grey: black
      out[i + 1] = a;   // alpha
    }
  }
  return out;
}

// -- PNG encoding ------------------------------------------------------------

function crc32(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function encodePng(size, grayAlpha) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 4;  // colour type: grayscale + alpha
  // 10..12: compression, filter, interlace — all 0

  // One filter byte (0 = None) per scanline.
  const stride = size * 2;
  const raw = Buffer.alloc((stride + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (stride + 1)] = 0;
    grayAlpha.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ]);
}

// ----------------------------------------------------------------------------

const sizes = [16, 32];
const encoded = {};
for (const s of sizes) encoded[s] = encodePng(s, drawIcon(s)).toString('base64');

const outPath = path.join(__dirname, '..', 'src', 'desktop', 'tray-icon.js');
fs.writeFileSync(outPath, `'use strict';
/**
 * Tray icon, generated by tools/make-tray-icon.js — do not hand-edit.
 *
 * Embedded as base64 rather than shipped as a binary asset so a clean checkout
 * always has it: the previous build referenced generated images that were
 * never committed and could not be packaged without running a generator first.
 *
 * Black plus alpha, so macOS can treat it as a template image and recolour it
 * for light, dark and highlighted menu bars.
 */

/** @type {Record<string, string>} size in points -> base64 PNG */
const TRAY_ICON_PNG = ${JSON.stringify(encoded, null, 2)};

module.exports = { TRAY_ICON_PNG };
`);

process.stdout.write(`wrote ${path.relative(process.cwd(), outPath)} (${sizes.map((s) => `${s}px ${encoded[s].length}b64`).join(', ')})\n`);
